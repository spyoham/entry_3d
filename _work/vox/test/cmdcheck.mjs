// the commands, by what they do: node test/cmdcheck.mjs
import { createSim } from '../sim.mjs';
const s = createSim({ consts: { AUTOSEED: 1234, TESTRUN: 1, AUTOMODE: 1, ANIMALS: 0 } });
const F = (k = 1) => { for (let i = 0; i < k; i++) s.frame(); };
let n = 0; while (s.peek('gState') !== 2 && n < 5000) { F(1); n++; }
F(30);
let fails = 0; const ok = (c, m) => { console.log(c ? 'ok  ' : 'FAIL', m); if (!c) fails++; };
const call = (f) => s.as('pen', f);
const last = () => String(s.peek('CHT').slice(-1)[0]);
const cmd = (t) => { const n0 = s.peek('CHT').length; call(() => s.fn.runCommand(t)); const ch = s.peek('CHT'); return ch.length > n0 || ch.length >= 6 ? last() : '(nothing)'; };
const P = (k) => s.peek(k);
const KEY = P('ITKEY'), id = (k) => KEY.indexOf(k);
const count = (k) => P('INVI').reduce((t, x, i) => t + (x === id(k) ? P('INVN')[i] : 0), 0);
const mobs = (k) => P('ET').filter(t => t > 0 && (k === undefined || P('MKEY')[t - 1] === k)).length;
let r;
// ---- weather
r = cmd('/weather clear'); ok(P('wthr') === 0, 'weather clear: ' + r);
r = cmd('/weather rain'); ok(P('wthr') === 1, 'weather rain: ' + r);
r = cmd('/weather thunder'); ok(P('wthr') === 2, 'weather thunder: ' + r);
r = cmd('/weather rain 600'); ok(P('wthr') === 1 && Math.abs(P('wthrT') - 600) < 2, `weather rain 600: wthrT ${P('wthrT')} ` + r);
r = cmd('/weather clear 1d'); ok(P('wthr') === 0, 'weather clear 1d: ' + r);
r = cmd('/weather snow'); ok(P('wthr') === 0 && /알 수 없|weather/.test(r), 'weather snow (no such): ' + r);
r = cmd('/weather'); ok(P('wthr') === 0, 'weather (nothing): ' + r);
r = cmd('/toggledownfall'); ok(P('wthr') === 1, 'toggledownfall: ' + r);
r = cmd('/toggledownfall'); ok(P('wthr') === 0, 'toggledownfall again: ' + r);
// ---- time (tday: 0..1 a day, 0 = 6:00, 1000 ticks)
const ticks = () => Math.round(P('tday') * 24000);
r = cmd('/time set day'); ok(ticks() === 1000, 'time set day: ' + ticks() + ' ' + r);
r = cmd('/time set noon'); ok(ticks() === 6000, 'time set noon: ' + ticks());
r = cmd('/time set night'); ok(ticks() === 13000, 'time set night: ' + ticks());
r = cmd('/time set midnight'); ok(ticks() === 18000, 'time set midnight: ' + ticks());
r = cmd('/time set 0'); ok(ticks() === 0, 'time set 0: ' + ticks());
r = cmd('/time set 30000'); ok(ticks() === 6000, 'time set 30000 (a day on): ' + ticks() + ' ' + r);
const d0 = P('dayN');
r = cmd('/time add 20000'); ok(ticks() === 2000 && P('dayN') === d0 + 1, `time add 20000: ${ticks()}, day ${d0} -> ${P('dayN')}`);
r = cmd('/time add 1d'); ok(ticks() === 2000 && P('dayN') === d0 + 2, `time add 1d: ${ticks()}, day ${P('dayN')} ` + r);
r = cmd('/time set 12000t'); ok(ticks() === 12000, 'time set 12000t: ' + ticks() + ' ' + r);
r = cmd('/time set 0.5d'); ok(ticks() === 12000, 'time set 0.5d: ' + ticks() + ' ' + r);
r = cmd('/time set 10s'); ok(ticks() === 200, 'time set 10s: ' + ticks() + ' ' + r);
r = cmd('/time query daytime'); ok(r.includes('200'), 'time query daytime: ' + r);
r = cmd('/time query day'); ok(r.includes(String(P('dayN'))), 'time query day: ' + r);
r = cmd('/time query gametime'); ok(/\d/.test(r), 'time query gametime: ' + r);
r = cmd('/time set dusk'); ok(/알 수 없|time/.test(r) || ticks() === 200, 'time set dusk (no such): ' + r);
// ---- targets
cmd('/gamemode survival'); cmd('/clear');
r = cmd('/give @a diamond 3'); ok(count('diamond') === 3, '@a give: ' + r);
r = cmd('/give @p diamond 1'); ok(count('diamond') === 4, '@p give: ' + r);
r = cmd('/give @r diamond 1'); ok(count('diamond') === 5, '@r give: ' + r);
r = cmd('/give @s diamond 1'); ok(count('diamond') === 6, '@s give: ' + r);
r = cmd('/give @e diamond 1'); ok(count('diamond') === 7, '@e give (the player among them): ' + r);
r = cmd('/give @e[type=zombie] diamond 1'); ok(count('diamond') === 7, '@e[type=zombie] give: nothing for the player: ' + r);
r = cmd('/give @a[distance=..5] diamond 1'); ok(count('diamond') === 8, '@a[distance=..5]: ' + r);
r = cmd('/give @a[distance=10..] diamond 1'); ok(count('diamond') === 8, '@a[distance=10..]: nobody: ' + r);
r = cmd('/give @x diamond 1'); ok(count('diamond') === 8, '@x (no such): ' + r);
r = cmd('/give diamond'); ok(count('diamond') === 8, '/give with no target: ' + r);
r = cmd('/clear @a diamond 3'); ok(count('diamond') === 5, '/clear @a diamond 3: ' + r);
r = cmd('/clear @s'); ok(count('diamond') === 0, '/clear @s: ' + r);
// mobs
cmd('/kill @e[type=!player]'); F(2);
const px = P('px'), pz = P('pz');
cmd('/summon cow ~3 ~ ~'); cmd('/summon cow ~-3 ~ ~'); cmd('/summon zombie ~ ~ ~6'); cmd('/summon pig ~20 ~ ~');
F(1);
ok(mobs('cow') === 2 && mobs('zombie') === 1 && mobs('pig') === 1, `summoned: cows ${mobs('cow')} zombies ${mobs('zombie')} pigs ${mobs('pig')}`);
r = cmd('/kill @e[type=cow,limit=1,sort=nearest]'); F(1); ok(mobs('cow') === 1, 'kill the nearest cow: ' + r);
r = cmd('/kill @e[distance=..10,type=!player]'); F(1); ok(mobs('cow') === 0 && mobs('zombie') === 0 && mobs('pig') === 1, `kill within 10 but the player: ${r} (pig ${mobs('pig')})`);
ok(P('hp') > 0 && P('dead') === 0, 'the player is alive');
r = cmd('/tp @e[type=pig] @s'); F(1);
const e = P('ET').findIndex(t => t > 0 && P('MKEY')[t - 1] === 'pig');
ok(e >= 0 && Math.hypot(P('EX')[e] - P('px'), P('EZ')[e] - P('pz')) < 1, 'tp the pig to me: ' + r);
r = cmd('/tp @s 100 80 100'); ok(Math.abs(P('px') - 100.5) < 0.01 && Math.abs(P('py') - 80) < 0.01, 'tp @s 100 80 100: ' + r);
r = cmd('/tp 0 70 0'); ok(Math.abs(P('px') - 0.5) < 0.01, 'tp 0 70 0: ' + r);
r = cmd('/tp @a ~ ~5 ~'); ok(Math.abs(P('py') - 75) < 0.01, 'tp @a ~ ~5 ~: ' + r);
r = cmd('/effect give @a speed 10 0'); ok(P('EFT')[0] > 0, 'effect give @a: ' + r);
r = cmd('/effect clear @a'); ok(P('EFT').every(t => t <= 0), 'effect clear @a: ' + r);
r = cmd('/gamemode creative @a'); ok(P('gameMode') === 1, 'gamemode creative @a: ' + r);
r = cmd('/gamemode 0'); ok(P('gameMode') === 0, 'gamemode 0: ' + r);
r = cmd('/gamemode c'); ok(P('gameMode') === 1, 'gamemode c: ' + r);
r = cmd('/gamemode sp'); ok(P('gameMode') === 3, 'gamemode sp: ' + r);
r = cmd('/gamemode survival @p'); ok(P('gameMode') === 0, 'gamemode survival @p: ' + r);
r = cmd('/xp add @a 3 levels'); ok(P('xpLevel') >= 3, 'xp add @a: ' + r);
r = cmd('/xp set @s 1 levels'); ok(P('xpLevel') === 1, 'xp set: ' + r);
r = cmd('/experience add @s 2 levels'); ok(P('xpLevel') === 3, 'experience add: ' + r);
r = cmd('/kill @a'); F(2); ok(P('dead') === 1, 'kill @a: ' + r);
call(() => s.fn.respawn()); F(5);
r = cmd('/difficulty peaceful'); ok(P('difficulty') === 0, 'difficulty peaceful: ' + r);
r = cmd('/difficulty 2'); ok(P('difficulty') === 2, 'difficulty 2: ' + r);
r = cmd('/say hi @a'); ok(r.includes('hi'), 'say: ' + r);
r = cmd('/spawnpoint @s 5 70 5'); ok(Math.abs(P('spawnX') - 5.5) < 0.6 && Math.abs(P('spawnY') - 70) < 0.6, 'spawnpoint: ' + r);
r = cmd('/gamerule doDaylightCycle false'); ok(P('grDay') === 0, 'gamerule: ' + r);
r = cmd('/gamerule doDaylightCycle'); ok(r.includes('false'), 'gamerule query: ' + r);
cmd('/gamerule doDaylightCycle true');
r = cmd('/execute as @a run give @s diamond 1'); ok(count('diamond') === 1, 'execute as @a run give @s: ' + r);
r = cmd('/execute if entity @a run give @s diamond 1'); ok(count('diamond') === 2, 'execute if entity @a: ' + r);
r = cmd('/execute unless entity @e[type=warden] run give @s diamond 1'); ok(count('diamond') === 3, 'execute unless entity: ' + r);
r = cmd('/TIME SET NOON'); ok(ticks() === 6000, 'upper case: ' + r);
r = cmd('/minecraft:time set day'); ok(ticks() === 1000, 'with the namespace: ' + r);
// ---- targets that find nobody, or are not targets
cmd('/gamemode creative');
r = cmd('/kill @e[type=zombie]'); ok(r.includes('찾지 못했'), 'nobody found: ' + r);
r = cmd('/give @x diamond 1'); ok(r.includes('알 수 없는 대상'), 'not a selector: ' + r);
r = cmd('/give diamond'); ok(r.startsWith('/give <대상>'), '/give with no target: ' + r);
r = cmd('/gamemode survival @e[type=cow]'); ok(P('gameMode') === 1, '/gamemode for cows leaves the player: ' + r);
cmd('/give @s jade 5');
r = cmd('/clear @e[type=pig] jade'); ok(count('jade') === 5, '/clear for a pig leaves the player: ' + r);
r = cmd('/xp add @e[type=pig] 5 levels'); const lv = P('xpLevel'); ok(true, '/xp for a pig: ' + r + ' level ' + lv);
r = cmd('/give 아무개 jade 1'); ok(count('jade') === 6, 'a name alone in this world is the player: ' + r);
r = cmd('/minecraft:time set day'); ok(ticks() === 1000, 'with the namespace (again): ' + r);
r = cmd('/tp @s @e[type=pig,limit=1]'); ok(Math.hypot(P('px') - P('EX')[e], P('pz') - P('EZ')[e]) < 0.01, 'tp to the pig: ' + r);
// a world made with commands off
s.poke('cheatsOn', 0);
r = cmd('/give @s diamond 1'); ok(r.includes('명령어를 쓸 수 없'), 'commands off: ' + r);
r = cmd('/help'); ok(!r.includes('쓸 수 없'), 'commands off: /help still: ' + r.slice(0, 30));
s.poke('cmdFromBlock', 1); r = cmd('/time set noon'); s.poke('cmdFromBlock', 0); ok(ticks() === 6000, 'commands off: a command block still works');
s.poke('cheatsOn', 1);
console.log(fails ? fails + ' FAILED' : 'all ok');
