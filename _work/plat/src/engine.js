// ================= 시간과 움직이는 발판 =================
// E를 누르고 있으면 스테이지의 시간이 거꾸로 간다 (주인공은 그대로)
function 시간_흐르기() {
    let 지금 = timer();
    간격 = 지금 - 지난_시각;
    지난_시각 = 지금;
    if (간격 > 0.05) {
        간격 = 0.05;
    }
    if (key(69) && (되감기_게이지 > 0 && 시간 > 0)) {
        시간 = 시간 - 간격;
        되감기_게이지 = 되감기_게이지 - 간격;
        if (시간 < 0) {
            시간 = 0;
        }
    } else {
        시간 = 시간 + 간격;
        if (!key(69) && 땅에_있음 == 1) {
            되감기_게이지 = 되감기_게이지 + 간격;
            if (되감기_게이지 > 되감기_최대) {
                되감기_게이지 = 되감기_최대;
            }
        }
    }
}
function 물체_움직이기() {
    let i = 2;
    let 비율 = 0;
    let x = 0;
    let y = 0;
    let z = 0;
    while (i <= 종류.length) {
        if (주기[i] > 0) {
            비율 = (1 - cosd(시간 / 주기[i] * 360)) / 2;
            x = 기준X[i] + 이동X[i] * 비율;
            y = 기준Y[i] + 이동Y[i] * 비율;
            z = 기준Z[i] + 이동Z[i] * 비율;
            // 밟고 있는 발판이 움직인 만큼 같이 움직인다
            if (밟은_물체 == i) {
                내X = 내X + (x - 물체X[i]);
                내Y = 내Y + (y - 물체Y[i]);
                내Z = 내Z + (z - 물체Z[i]);
            }
            물체X[i] = x;
            물체Y[i] = y;
            물체Z[i] = z;
        }
        i = i + 1;
    }
}

// ================= 주인공 =================
function 입력_받기() {
    let 앞 = 0;
    let 옆 = 0;
    let 빠르기 = 이동_속도;
    let 가속 = 간격 * 12;
    if (key(37)) {
        카메라_각도 = 카메라_각도 - 카메라_회전_속도 * 간격;
    }
    if (key(39)) {
        카메라_각도 = 카메라_각도 + 카메라_회전_속도 * 간격;
    }
    if (key(87)) {
        앞 = 앞 + 1;
    }
    if (key(83)) {
        앞 = 앞 - 1;
    }
    if (key(68)) {
        옆 = 옆 + 1;
    }
    if (key(65)) {
        옆 = 옆 - 1;
    }
    // 대각선으로 갈 때 더 빨라지지 않게
    if (앞 != 0 && 옆 != 0) {
        빠르기 = 이동_속도 * 0.7;
    }
    // 공중에서는 방향을 천천히 바꾼다
    if (땅에_있음 == 0) {
        가속 = 간격 * 5;
    }
    if (가속 > 1) {
        가속 = 1;
    }
    속도X = 속도X + ((옆 * 코사인 + 앞 * 사인) * 빠르기 - 속도X) * 가속;
    속도Z = 속도Z + ((앞 * 코사인 - 옆 * 사인) * 빠르기 - 속도Z) * 가속;
    // 점프: 조금 일찍 눌러도, 발판 끝을 막 벗어났어도 된다
    이전_점프키 = 점프키;
    if (key(32)) {
        점프키 = 1;
    } else {
        점프키 = 0;
    }
    if (점프키 == 1 && 이전_점프키 == 0) {
        점프_대기 = 0.15;
    }
    if (점프_대기 > 0) {
        점프_대기 = 점프_대기 - 간격;
        if (공중_시간 < 0.12) {
            속도Y = 점프_힘;
            공중_시간 = 1;
            남은_점프 = 1;
            점프_대기 = 0;
        } else {
            if (남은_점프 > 0) {
                속도Y = 두번째_점프_힘;
                남은_점프 = 남은_점프 - 1;
                점프_대기 = 0;
            }
        }
    }
    // 점프 키를 일찍 떼면 낮게 뛴다
    if (점프키 == 0 && 속도Y > 0) {
        속도Y = 속도Y - 중력 * 1.5 * 간격;
    }
}
function 주인공_움직이기() {
    let i = 2;
    속도Y = 속도Y - 중력 * 간격;
    if (속도Y < -18) {
        속도Y = -18;
    }
    이전_발 = 내Y;
    내X = 내X + 속도X * 간격;
    내Y = 내Y + 속도Y * 간격;
    내Z = 내Z + 속도Z * 간격;
    땅에_있음 = 0;
    밟은_물체 = 0;
    while (i <= 종류.length) {
        if (내X + 0.3 > 물체X[i]) {
            if (내X - 0.3 < 물체X[i] + 가로[i]) {
                if (내Z + 0.3 > 물체Z[i]) {
                    if (내Z - 0.3 < 물체Z[i] + 세로[i]) {
                        if (내Y < 물체Y[i] + 높이[i]) {
                            if (내Y + 1.2 > 물체Y[i]) {
                                물체에_닿음(i);
                            }
                        }
                    }
                }
            }
        }
        i = i + 1;
    }
    if (땅에_있음 == 1) {
        공중_시간 = 0;
        남은_점프 = 1;
    } else {
        공중_시간 = 공중_시간 + 간격;
    }
    if (내Y < 낙하_높이) {
        주인공_되살리기();
    }
    주인공_상자_옮기기();
}
function 주인공_상자_옮기기() {
    물체X[1] = 내X - 0.3;
    물체Y[1] = 내Y;
    물체Z[1] = 내Z - 0.3;
}
function 물체에_닿음(i) {
    if (종류[i] == '발판') {
        발판에_부딪힘(i);
    }
    if (종류[i] == '가시') {
        주인공_되살리기();
    }
    if (종류[i] == '태엽' && 상태[i] == 0) {
        상태[i] = 2;
        모은_태엽 = 모은_태엽 + 1;
    }
    if (종류[i] == '깃발' && 상태[i] == 0) {
        상태[i] = 1;
        색[i] = 10;
        시작X = 물체X[i] + 0.1;
        시작Y = 물체Y[i];
        시작Z = 물체Z[i] + 0.1;
    }
    if (종류[i] == '목표') {
        스테이지_끝 = 1;
    }
}
function 발판에_부딪힘(i) {
    let 윗면 = 물체Y[i] + 높이[i];
    let 왼쪽 = 내X + 0.3 - 물체X[i];
    let 오른쪽 = 물체X[i] + 가로[i] - (내X - 0.3);
    let 앞쪽 = 내Z + 0.3 - 물체Z[i];
    let 뒤쪽 = 물체Z[i] + 세로[i] - (내Z - 0.3);
    let 가장_얕은 = 왼쪽;
    if (이전_발 >= 윗면 - 0.25) {
        // 위에서 내려왔다: 올라선다 (모서리에 살짝 걸려도 올려 준다)
        내Y = 윗면;
        if (속도Y < 0) {
            속도Y = 0;
        }
        땅에_있음 = 1;
        밟은_물체 = i;
    } else {
        if (이전_발 + 1.2 <= 물체Y[i] + 0.05) {
            // 아래에서 머리를 부딪혔다
            내Y = 물체Y[i] - 1.2;
            if (속도Y > 0) {
                속도Y = 0;
            }
        } else {
            // 옆에서 부딪혔다: 가장 얕게 들어간 쪽으로 밀어낸다
            if (오른쪽 < 가장_얕은) {
                가장_얕은 = 오른쪽;
            }
            if (앞쪽 < 가장_얕은) {
                가장_얕은 = 앞쪽;
            }
            if (뒤쪽 < 가장_얕은) {
                가장_얕은 = 뒤쪽;
            }
            if (가장_얕은 == 왼쪽) {
                내X = 내X - 왼쪽;
            } else {
                if (가장_얕은 == 오른쪽) {
                    내X = 내X + 오른쪽;
                } else {
                    if (가장_얕은 == 앞쪽) {
                        내Z = 내Z - 앞쪽;
                    } else {
                        내Z = 내Z + 뒤쪽;
                    }
                }
            }
        }
    }
}
// 발밑에서 가장 높은 발판: 거기에 그림자를 그린다
function 그림자_찾기() {
    let i = 2;
    let 가장_높은 = -99999;
    그림자_물체 = 0;
    while (i <= 종류.length) {
        if (종류[i] == '발판') {
            if (내X > 물체X[i] && 내X < 물체X[i] + 가로[i]) {
                if (내Z > 물체Z[i] && 내Z < 물체Z[i] + 세로[i]) {
                    if (물체Y[i] + 높이[i] <= 내Y + 0.1 && 물체Y[i] + 높이[i] > 가장_높은) {
                        가장_높은 = 물체Y[i] + 높이[i];
                        그림자_물체 = i;
                    }
                }
            }
        }
        i = i + 1;
    }
}

