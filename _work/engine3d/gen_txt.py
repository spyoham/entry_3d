def plain(text):
    out = []
    for ch in text:
        o = ord(ch)
        if o > 0x2000 and not (0xAC00 <= o <= 0xD7A3):   # 이모지/기호 제거, 한글은 유지
            continue
        out.append(ch)
    t = re.sub(r'%\d+', '( )', ''.join(out))
    t = re.sub(r'  +', '  ', t).strip()
    return t

